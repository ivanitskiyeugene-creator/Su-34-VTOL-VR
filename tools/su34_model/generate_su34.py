def interp(table, z):
    """Piecewise linear lookup, table sorted by z descending or ascending."""
    pts = sorted(table)
    if z <= pts[0][0]:
        return pts[0][1]
    if z >= pts[-1][0]:
        return pts[-1][1]
    for (z0, v0), (z1, v1) in zip(pts, pts[1:]):
        if z0 <= z <= z1:
            t = (z - z0) / (z1 - z0)
            return v0 + (v1 - v0) * t
    return pts[-1][1]


def hull_exponent(z: float) -> float:
    """2.2 at the radome, 2.9 on the wide flat aft body."""
    t = np.clip((11.0 - z) / 13.0, 0.0, 1.0)
    return 2.2 + 0.75 * float(t)


# ------------------------------------------------------------------- surfaces
def section_ring(z, hw, top, bot, n, count=56):
    cy = (top + bot) / 2.0
    hh = (top - bot) / 2.0
    pts = []
    for k in range(count):
        t = 2 * math.pi * k / count
        ct, st = math.cos(t), math.sin(t)
        x = hw * math.copysign(abs(ct) ** (2.0 / n), ct)
        y = cy + hh * math.copysign(abs(st) ** (2.0 / n), st)
        pts.append(v(x, y, z))
    return pts


STATIONS = []
_z = np.linspace(TAIL_Z, NOSE_Z, 150)
for _zi in _z:
    _zi = float(_zi)
    STATIONS.append((_zi, interp(HALF_WIDTH, _zi), interp(TOP_LINE, _zi),
                     max(0.02, interp(SIDE_BOT, _zi)), hull_exponent(_zi)))
STATIONS.sort(key=lambda s: -s[0])


def station_at(z: float):
    for z0, hw0, t0, b0, n0 in STATIONS:
        pass
    best = min(STATIONS, key=lambda s: abs(s[0] - z))
    return best[1], best[2], best[3], best[4]


def skin_top_y(z: float, x: float) -> float:
    hw, top, bot, n = station_at(z)
    cy = (top + bot) / 2.0
    hh = (top - bot) / 2.0
    t = min(abs(x) / max(hw, 1e-6), 1.0)
    cos_t = t ** (n / 2.0)
    sin_t = math.sqrt(max(1.0 - cos_t * cos_t, 0.0))
    return cy + hh * (sin_t ** (2.0 / n))


def sill_y(z: float) -> float:
    return skin_top_y(z, CANOPY_HALF_WIDTH) - 0.01


# -------------------------------------------------------------------- fuselage
def build_fuselage(mesh: Mesh) -> None:
    rings, zs = [], []
    for z, hw, top, bot, n in STATIONS:
        rings.append(section_ring(z, hw, top, bot, n))
        zs.append(z)
    count = len(rings[0])

    def skip(section: int, segment: int) -> bool:
        z = zs[section]
        if not (COCKPIT_Z0 <= z <= COCKPIT_Z1):
            return False
        a = rings[section][segment]
        b = rings[section][(segment + 1) % count]
        cut = sill_y(z) - 0.03
        for p in (a, b):
            if abs(p[0]) > CANOPY_HALF_WIDTH + 0.10:
                return False
            if p[1] < cut:
                return False
        return True

    body = [r for r, s in zip(rings, STATIONS) if s[0] <= 9.60]
    radome = [r for r, s in zip(rings, STATIONS) if s[0] >= 9.50]

    p = mesh.loft("Su34_Radome", "Su34_Radome", radome, cap_start=True,
                  cap_end=False)
    mesh.orient(p, lambda c: v(0, 0.8, c[2]))
    start = [i for i, s in enumerate(STATIONS) if s[0] <= 9.60][0]
    p = mesh.loft("Su34_Fuselage", "Su34_Camo", body, cap_start=False,
                  cap_end=True, skip=lambda s, i: skip(start + s, i))
    mesh.orient(p, lambda c: v(0, 0.8, c[2]))

    # belly in the underside colour: a thin open shell just outside the hull
    belly = []
    for z, hw, top, bot, n in STATIONS:
        if z > 9.4 or z < -9.4:
            continue
        cy = (top + bot) / 2.0
        hh = (top - bot) / 2.0
        ring = []
        for k in range(24):
            t = math.radians(196.0) + math.radians(148.0) * k / 23.0
            ct, st = math.cos(t), math.sin(t)
            x = hw * 1.012 * math.copysign(abs(ct) ** (2.0 / n), ct)
            y = cy + hh * 1.012 * math.copysign(abs(st) ** (2.0 / n), st)
            ring.append(v(x, y, z))
        belly.append(ring)
    p = mesh.loft("Su34_Belly", "Su34_Underside", belly, closed_ring=False)
    mesh.orient(p, lambda c: v(0.0, 0.2, c[2]))


# --------------------------------------------------------------------- canopy
CANOPY_SECTIONS = [
    (7.35, 2.26), (6.85, 2.52), (6.30, 2.69), (5.80, 2.78), (5.30, 2.84),
    (4.80, 2.88), (4.30, 2.89), (3.80, 2.86),
]


def canopy_crown(z: float) -> float:
    return interp(CANOPY_SECTIONS, z)


def canopy_ring(z: float, crown: float, n: int = 26, scale: float = 1.0):
    base = sill_y(z)
    hw = CANOPY_HALF_WIDTH * scale
    ring = []
    for k in range(n + 1):
        t = math.pi * k / n
        y = base + (crown - base) * max(0.0, math.sin(t)) ** 0.65
        ring.append(v(hw * math.cos(t), y, z))
    return ring


def build_canopy(mesh: Mesh) -> None:
    zs = [3.80, 4.30, 4.80, 5.30, 5.80, 6.30, 6.85, 7.35]
    rings = [canopy_ring(z, canopy_crown(z)) for z in zs]
    p = mesh.loft("Su34_Canopy", "Su34_Glass", rings, closed_ring=False)
    mesh.orient(p, lambda c: v(0, sill_y(c[2]) - 0.2, c[2]))

    # frames: windscreen bow, canopy hinge and the rear arch
    for z, rad in ((3.83, 0.05), (7.32, 0.05)):
        r = canopy_ring(z, canopy_crown(z), 26, 1.004)
        for k in range(len(r) - 1):
            a, b = r[k], r[k + 1]
            mesh.cylinder("Su34_CanopyFrame", "Su34_Frame",
                          (a + b) / 2.0 - v(0, 0.012, 0.03),
                          (a + b) / 2.0 - v(0, 0.012, -0.03),
                          rad * 0.5, rad * 0.5, segments=6, caps=False)
    # centre rail
    rail = [v(0.0, canopy_crown(z) + 0.012, z) for z in (3.83, 4.6, 5.4, 6.2, 7.0, 7.33)]
    for a, b in zip(rail, rail[1:]):
        mesh.cylinder("Su34_CanopyRail", "Su34_Frame", a, b, 0.028, 0.028,
                      segments=6, caps=False)
    # rear fairing: blends the canopy into the spine
    fair = [canopy_ring(z, canopy_crown(3.80) - 0.10, 26, 0.99 * k)
            for z, k in ((3.80, 1.0), (3.60, 0.80), (3.45, 0.55))]
    p = mesh.loft("Su34_CanopyFairing", "Su34_Camo", fair, closed_ring=False)
    mesh.orient(p, lambda c: v(0, sill_y(c[2]) - 0.2, c[2]))


