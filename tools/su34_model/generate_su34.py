def interp(table, z):
    """Piecewise linear lookup, table sorted by z descending or ascending."""
    pts = sorted(table)
    if z <= pts[0][0]:
        return pts[0][1]
    if z >= pts[-1][0]:
        return pts[-1][1]
    for (z0, v0), (z1, v1) in zip(pts, pts[1:]):
        if z0 <= z <= z1:
            t = (z - z0) / (z1 - z0)
            return v0 + (v1 - v0) * t
    return pts[-1][1]


def hull_exponent(z: float) -> float:
    """2.1 at the radome, 4.3 on the slab-sided mid body.

    High exponents give the flat deck and vertical sides the Su-34 has; a
    round exponent turns the fuselage into a tube.
    """
    if z > 11.30:                       # rounded radome tip
        return 2.4
    if z > 8.20:                        # flat-topped duckbill nose
        return 3.1
    if z > 6.00:                        # cockpit barrel
        return 2.9
    t = float(np.clip((6.0 - z) / 6.0, 0.0, 1.0))
    n = 2.9 + 1.4 * t
    if z < -8.0:
        n = max(3.2, n - (-8.0 - z) * 0.10)
    return n


# ------------------------------------------------------------------- surfaces
SHOULDER_GAIN = 0.55          # depth of the deck edge over the engine bay
SHOULDER_ONSET = 1.42
SHOULDER_DEPTH = 0.56


def shoulder_gain(z: float) -> float:
    """The hard deck edge only exists over the engine bay; the cockpit barrel
    and the nose stay round so the canopy still sits on skin."""
    t = min(max((1.0 - z) / 3.0, 0.0), 1.0)
    return 0.10 + (SHOULDER_GAIN - 0.10) * t * t * (3.0 - 2.0 * t)


def shoulder(y: float, z: float = -4.0) -> float:
    """Head-on drawing: the hull is 2.2 m wide just under the deck edge and
    only 1.39 m wide 0.2 m higher, so the top corners roll over hard."""
    t = min(max((y - SHOULDER_ONSET) / SHOULDER_DEPTH, 0.0), 1.0)
    return 1.0 - shoulder_gain(z) * t ** 0.7


def section_ring(z, hw, top, bot, n, count=56):
    cy = (top + bot) / 2.0
    hh = (top - bot) / 2.0
    pts = []
    for k in range(count):
        t = 2 * math.pi * k / count
        ct, st = math.cos(t), math.sin(t)
        x = hw * math.copysign(abs(ct) ** (2.0 / n), ct)
        y = cy + hh * math.copysign(abs(st) ** (2.0 / n), st)
        pts.append(v(x * shoulder(y, z), y, z))
    return pts


STATIONS = []
_z = np.linspace(TAIL_Z, NOSE_Z, 150)
for _zi in _z:
    _zi = float(_zi)
    STATIONS.append((_zi, interp(HALF_WIDTH, _zi), interp(TOP_LINE, _zi),
                     max(0.02, interp(KEEL, _zi)), hull_exponent(_zi)))
STATIONS.sort(key=lambda s: -s[0])


def station_at(z: float):
    for z0, hw0, t0, b0, n0 in STATIONS:
        pass
    best = min(STATIONS, key=lambda s: abs(s[0] - z))
    return best[1], best[2], best[3], best[4]


def skin_top_y(z: float, x: float) -> float:
    """Height of the hull skin above ``x``: inverts the superellipse *and* the
    station's shoulder, which shrinks the section as it rises."""
    hw, top, bot, n = station_at(z)
    cy = (top + bot) / 2.0
    hh = (top - bot) / 2.0
    t = min(abs(x) / max(hw, 1e-6), 1.0)
    y = top
    for _ in range(10):
        s = max(1e-3, shoulder(y, z))
        cos_t = min(t / s, 1.0) ** (n / 2.0)
        sin_t = math.sqrt(max(1.0 - cos_t * cos_t, 0.0))
        y = cy + hh * (sin_t ** (2.0 / n))
    return y


def sill_y(z: float) -> float:
    return skin_top_y(z, CANOPY_HALF_WIDTH) - 0.01


# -------------------------------------------------------------------- fuselage
def build_fuselage(mesh: Mesh) -> None:
    rings, zs = [], []
    for z, hw, top, bot, n in STATIONS:
        rings.append(section_ring(z, hw, top, bot, n))
        zs.append(z)
    count = len(rings[0])

    def skip(section: int, segment: int) -> bool:
        z = zs[section]
        if not (COCKPIT_Z0 <= z <= COCKPIT_Z1):
            return False
        a = rings[section][segment]
        b = rings[section][(segment + 1) % count]
        cut = sill_y(z) - 0.03
        for p in (a, b):
            if abs(p[0]) > CANOPY_HALF_WIDTH + 0.10:
                return False
            if p[1] < cut:
                return False
        return True

    body = [r for r, s in zip(rings, STATIONS) if s[0] <= 9.60]
    radome = [r for r, s in zip(rings, STATIONS) if s[0] >= 9.50]

    p = mesh.loft("Su34_Radome", "Su34_Camo", radome, cap_start=True,
                  cap_end=False)
    mesh.orient(p, lambda c: v(0, 0.8, c[2]))
    start = [i for i, s in enumerate(STATIONS) if s[0] <= 9.60][0]
    p = mesh.loft("Su34_Fuselage", "Su34_Camo", body, cap_start=False,
                  cap_end=True, skip=lambda s, i: skip(start + s, i))
    mesh.orient(p, lambda c: v(0, 0.8, c[2]))

    # chine strakes along the forward fuselage: a flat bevelled edge at the
    # widest point of the nose section
    for side in (-1, 1):
        zs = np.linspace(7.40, 11.30, 12)
        upper, lower = [], []
        for z in zs:
            hw, top, bot, n = station_at(z)
            y = 0.5 * (top + bot) - 0.04
            w = hw * 1.004
            upper.append(v(side * (w + 0.105), y + 0.022, z))
            lower.append(v(side * w, y - 0.060, z))
        mesh.quad_strip("Su34_Chine_L" if side < 0 else "Su34_Chine_R", "Su34_Camo",
                        upper, lower, double_sided=True)

    # belly in the underside colour: a thin open shell just outside the hull
    belly = []
    for z, hw, top, bot, n in STATIONS:
        if z > 9.4 or z < -9.4:
            continue
        cy = (top + bot) / 2.0
        hh = (top - bot) / 2.0
        ring = []
        for k in range(24):
            t = math.radians(196.0) + math.radians(148.0) * k / 23.0
            ct, st = math.cos(t), math.sin(t)
            x = hw * 1.012 * math.copysign(abs(ct) ** (2.0 / n), ct)
            y = cy + hh * 1.012 * math.copysign(abs(st) ** (2.0 / n), st)
            ring.append(v(x, y, z))
        belly.append(ring)
    p = mesh.loft("Su34_Belly", "Su34_Underside", belly, closed_ring=False)
    mesh.orient(p, lambda c: v(0.0, 0.2, c[2]))


