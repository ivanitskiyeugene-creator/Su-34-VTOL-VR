# --------------------------------------------------------------------- decals
def build_decals(mesh: Mesh) -> None:
    """Red stars and the bort number, as flat quads laid on the skin."""
    uv = [(0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0)]

    # fin stars, outboard face
    for side in (-1, 1):
        x = side * 2.205
        q = [v(x, 3.40, -5.15), v(x, 3.40, -6.05),
             v(x, 4.30, -6.05), v(x, 4.30, -5.15)]
        mesh.quad("Su34_DecalStarFin", "Su34_Star",
                  q if side > 0 else list(reversed(q)), uv)

    # wing stars, both surfaces near the tip
    for side in (-1, 1):
        for dy, name in ((0.012, "Su34_DecalStarWingTop"),
                         (-0.012, "Su34_DecalStarWingBot")):
            y = 1.304 + dy
            q = [v(side * 4.55, y, -2.60), v(side * 5.45, y, -2.60),
                 v(side * 5.45, y, -3.50), v(side * 4.55, y, -3.50)]
            if (dy > 0) != (side > 0):
                q = list(reversed(q))
            mesh.quad(name, "Su34_Star", q, uv)

    # bort number on the forward fuselage, one quad per side
    for side in (-1, 1):
        x = side * 0.985
        q = [v(x, 0.84, 9.10), v(x, 0.84, 8.10),
             v(x, 1.52, 8.10), v(x, 1.52, 9.10)]
        if side < 0:
            q = list(reversed(q))
        mesh.quad("Su34_DecalNumber", "Su34_Number", q, uv)


# ------------------------------------------------------------------------ main
def build() -> Mesh:
    mesh = Mesh()
    build_fuselage(mesh)
    build_cockpit(mesh)
    build_canopy(mesh)
    build_wings(mesh)
    build_canards(mesh)
    build_stabilators(mesh)
    build_fins(mesh)
    build_engines(mesh)
    build_gear(mesh)
    build_pylons(mesh)
    build_details(mesh)
    build_decals(mesh)
    apply_box_uv(mesh, tile_size=2.6)
    return mesh


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    mesh = build()
    obj = os.path.join(OUT_DIR, "su34.obj")
    write_obj(obj, mesh, "su34.mtl")
    write_mtl(os.path.join(OUT_DIR, "su34.mtl"), MATERIALS)
    verts = sum(len(p.vertices) for p in mesh.parts)
    tris = sum(len(p.faces) for p in mesh.parts)
    allv = np.array([q for p in mesh.parts for q in p.vertices])
    lo, hi = allv.min(axis=0), allv.max(axis=0)
    print(f"{len(mesh.parts)} parts, {verts} verts, {tris} tris")
    print("bbox  x %.2f..%.2f  y %.2f..%.2f  z %.2f..%.2f"
          % (lo[0], hi[0], lo[1], hi[1], lo[2], hi[2]))
    print("size  %.2f x %.2f x %.2f m  (span x height x length)"
          % (hi[0] - lo[0], hi[1] - lo[1], hi[2] - lo[2]))


if __name__ == "__main__":
    main()
